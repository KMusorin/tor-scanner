#!/bin/sh
set -e

CONF_DIR=/etc/tor/torrc.d
mkdir -p "$CONF_DIR"

echo "Running tor-scanner with user parameters: $@"
if ! /usr/local/bin/tor-scanner "$@" -output "$CONF_DIR/bridges.conf"; then
    if [ ! -f "$CONF_DIR/bridges.conf" ]; then
        echo "Failed to generate $CONF_DIR/bridges.conf, no fallback available."
        exit 1
    fi
    echo "tor-scanner failed; falling back to existing $CONF_DIR/bridges.conf"
fi

{
    echo "# Generated by entrypoint.sh"
    echo "ClientTransportPlugin obfs4 exec /usr/local/bin/lyrebird managed"
    if [ -n "$EXIT_NODES" ]; then
        echo "ExitNodes $EXIT_NODES"
    fi
    if [ -n "$EXCLUDE_EXIT_NODES" ]; then
        echo "ExcludeExitNodes $EXCLUDE_EXIT_NODES"
    fi
    if [ -n "$STRICT_NODES" ]; then
        echo "StrictNodes $STRICT_NODES"
    fi
    if [ -n "$CLIENT_USE_IPV6" ]; then
        echo "ClientUseIPv6 $CLIENT_USE_IPV6"
    fi
} > "$CONF_DIR/options.conf"

echo "Starting Tor with configuration: /etc/tor/torrc"
exec tor -f /etc/tor/torrc
